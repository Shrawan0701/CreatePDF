// Resize the supplied brand asset into platform icons; no redesign or remote processing.
// Run locally and commit the output. Vercel builds do not need a browser executable.
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright-core';

const source = await readFile('src/assets/createpdf.png');
const version = createHash('sha256').update(source).digest('hex').slice(0, 10);
const entries = [
  { key: 'icon192', size: 192, purpose: 'any' },
  { key: 'icon512', size: 512, purpose: 'any' },
  { key: 'maskable512', size: 512, purpose: 'maskable' },
  { key: 'apple180', size: 180 },
  { key: 'favicon32', size: 32 },
];
await mkdir('public/icons', { recursive: true });
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge', headless: true });
try {
  const page = await browser.newPage();
  for (const entry of entries) {
    const png = await page.evaluate(async ({ data, size, maskable }) => {
      const image = new Image(); image.src = `data:image/png;base64,${data}`; await image.decode();
      const canvas = document.createElement('canvas'); canvas.width = canvas.height = size;
      const context = canvas.getContext('2d');
      if (maskable) { context.fillStyle = '#f7f9f5'; context.fillRect(0, 0, size, size); }
      // A square of side 0.56 fits entirely inside the standard 0.4-radius safe circle.
      const extent = size * (maskable ? .56 : 1);
      const scale = Math.min(extent / image.width, extent / image.height);
      const width = image.width * scale, height = image.height * scale;
      context.imageSmoothingEnabled = true; context.imageSmoothingQuality = 'high';
      context.drawImage(image, (size - width) / 2, (size - height) / 2, width, height);
      return canvas.toDataURL('image/png').split(',')[1];
    }, { data: source.toString('base64'), size: entry.size, maskable: entry.purpose === 'maskable' });
    entry.url = `/icons/createpdf-${version}-${entry.key}.png`;
    await writeFile(`public${entry.url}`, Buffer.from(png, 'base64'));
  }
} finally { await browser.close(); }

const icons = Object.fromEntries(entries.map((entry) => [entry.key, entry.url]));
const manifest = JSON.parse(await readFile('public/manifest.json', 'utf8'));
manifest.id = '/'; manifest.scope = '/';
manifest.icons = entries.filter((entry) => entry.purpose).map((entry) => ({ src: entry.url, sizes: `${entry.size}x${entry.size}`, type: 'image/png', purpose: entry.purpose }));
await writeFile('public/manifest.json', JSON.stringify(manifest, null, 2) + '\n');
const index = (await readFile('index.html', 'utf8'))
  .replace(/<link rel="manifest"[^>]*\/>/, `<link rel="manifest" href="/manifest.json?v=${version}" />`)
  .replace(/<link rel="apple-touch-icon"[^>]*\/>/, `<link rel="apple-touch-icon" sizes="180x180" href="${icons.apple180}" />`)
  .replace(/<link rel="icon"[^>]*\/>/, `<link rel="icon" type="image/png" sizes="32x32" href="${icons.favicon32}" />`);
await writeFile('index.html', index);
await writeFile('src/data/brand.js', `// Generated by npm run assets:icons from src/assets/createpdf.png.\nexport const BRAND_ICONS = ${JSON.stringify({ version, ...icons }, null, 2)};\n`);
console.log(`Generated app icons from createpdf.png (${version}); updated manifest, favicon and Apple touch icon.`);
